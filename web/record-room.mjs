import {chromium} from '@playwright/test';
import fs from 'node:fs/promises';
const out=process.argv[2]??'../docs/lofi-mood/recording';await fs.mkdir(out,{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true});
const context=await browser.newContext({viewport:{width:1440,height:1050},recordVideo:{dir:out+'/raw-video',size:{width:1440,height:1050}}});
const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5173/room.html');await page.waitForFunction(()=>window.lofiRoom?.ready());await page.waitForTimeout(1200);
await page.screenshot({path:out+'/room-idle.png',fullPage:true});
const before=await page.evaluate(()=>lofiRoom.snapshot());
const start=Date.now();await page.getByRole('button',{name:'Say hello',exact:true}).click();
await page.waitForFunction(()=>lofiRoom.snapshot().interaction.elapsed>=1.5);
await page.screenshot({path:out+'/room-greeting.png',fullPage:true});
await page.waitForFunction(()=>lofiRoom.snapshot().interaction.completed===1);await page.waitForTimeout(900);
await page.screenshot({path:out+'/room-returned.png',fullPage:true});
await page.getByRole('button',{name:'Behind the scene'}).click();
await page.locator('#inspector').scrollIntoViewIfNeeded();
await page.evaluate(()=>{lofiRoom.greet();for(let i=0;i<5;i++)lofiRoom.greet();});
await page.waitForTimeout(1700);await page.screenshot({path:out+'/transition-inspector.png',fullPage:true});
await page.waitForFunction(()=>lofiRoom.snapshot().interaction.completed===3);await page.waitForTimeout(600);
await page.getByRole('button',{name:'Center view',exact:true}).click();
await page.evaluate(()=>scrollTo(0,0));await page.waitForTimeout(600);
await page.screenshot({path:out+'/room-centered.png',fullPage:true});
const after=await page.evaluate(()=>lofiRoom.snapshot());
await fs.writeFile(out+'/demo-evidence.json',JSON.stringify({recordedAt:new Date().toISOString(),elapsedMs:Date.now()-start,errors,before,after},null,2));
const video=page.video();await context.close();await video.saveAs(out+'/demo.webm');await browser.close();
console.log('Saved actual browser recording and evidence.');
